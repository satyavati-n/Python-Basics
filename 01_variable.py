# PYTHON VARIABLES

# A variable is a name used to store a value.

name = "Satyavati"
age = 22
height = 5.5

print(name)
print(age)
print(height)


# Changing a variable

age = 23
print("New age:", age)


# Multiple variables

x = 10
y = 20

print("x =", x)
print("y =", y)


# Assigning multiple values

a, b, c = 10, 20, 30

print(a)
print(b)
print(c)


# Same value to multiple variables

x = y = z = 100

print(x, y, z)


# Checking the type of a variable

number = 25
print(type(number))