# PYTHON OPERATORS

a = 10
b = 3



# Arithmetic Operators

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor Division:", a // b)
print("Modulus:", a % b)
print("Power:", a ** b)



# Comparison Operators


print(a == b)
print(a != b)
print(a > b)
print(a < b)
print(a >= b)
print(a <= b)



# Logical Operators


age = 20

print(age > 18 and age < 30)
print(age < 18 or age > 60)
print(not(age > 18))



# Assignment Operators


x = 10

x += 5
print(x)

x -= 2
print(x)

x *= 2
print(x)

x /= 2
print(x)